import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const checkOnly = process.argv.includes("--check");
const manifest = JSON.parse(await readFile(resolve(repositoryRoot, "native-targets.json"), "utf8"));
const rootPackagePath = resolve(repositoryRoot, manifest.rootPackage, "package.json");
const rootPackage = JSON.parse(await readFile(rootPackagePath, "utf8"));
const license = await readFile(resolve(repositoryRoot, "LICENSE.md"), "utf8");
const thirdPartyLicenses = await readFile(resolve(repositoryRoot, "THIRD_PARTY_LICENSES.html"), "utf8");
const outputs = new Map();

rootPackage.optionalDependencies = Object.fromEntries(
  manifest.targets.map((target) => [target.packageName, rootPackage.version])
);
outputs.set(rootPackagePath, `${JSON.stringify(rootPackage, null, 2)}\n`);

const packageMap = {};
for (const target of manifest.targets) {
  packageMap[runtimeKey(target)] = target.packageName;
  const directory = resolve(repositoryRoot, manifest.nativePackageRoot, target.packageDirectory);
  const nativePackage = {
    name: target.packageName,
    version: rootPackage.version,
    description: `Native Node-API binary for @sjunepark/ytm on ${target.npmPlatform}-${target.npmArch}.`,
    main: target.artifactFile,
    files: [target.artifactFile, "LICENSE.md", "THIRD_PARTY_LICENSES.html"],
    os: [target.npmPlatform],
    cpu: [target.npmArch],
    engines: { node: ">=22" },
    publishConfig: { access: "public" },
    repository: {
      ...rootPackage.repository,
      directory: `${manifest.nativePackageRoot}/${target.packageDirectory}`
    },
    license: rootPackage.license
  };
  if (target.libc) nativePackage.libc = [target.libc];
  outputs.set(resolve(directory, "package.json"), `${JSON.stringify(nativePackage, null, 2)}\n`);
  outputs.set(resolve(directory, "README.md"), `# \`${target.packageName}\`\n\nThis generated package contains the ${target.rustTarget} native artifact for \`@sjunepark/ytm\`. Install the root package instead of depending on this package directly.\n`);
  outputs.set(resolve(directory, "LICENSE.md"), license);
  outputs.set(resolve(directory, "THIRD_PARTY_LICENSES.html"), thirdPartyLicenses);
}

const loader = `// Generated by scripts/generate-native-packages.mjs from native-targets.json.\nconst { existsSync } = require("node:fs");\nconst { join } = require("node:path");\n\nconst packageByTarget = ${JSON.stringify(packageMap, null, 2)};\n\nconst local = join(__dirname, "ytm.node");\nif (existsSync(local)) {\n  module.exports = require(local);\n} else {\n  const libc = process.platform === "linux"\n    ? (process.report?.getReport()?.header?.glibcVersionRuntime ? "gnu" : "musl")\n    : null;\n  const key = [process.platform, process.arch, libc].filter(Boolean).join("-");\n  const packageName = packageByTarget[key];\n  if (!packageName) throw new Error(\`@sjunepark/ytm does not support \${key}.\`);\n  try {\n    module.exports = require(packageName);\n  } catch (cause) {\n    const error = new Error(\`The native ytm package for \${key} is not installed correctly.\`);\n    error.cause = cause;\n    throw error;\n  }\n}\n`;
outputs.set(resolve(repositoryRoot, manifest.rootPackage, "src/native.cjs"), loader);

const stale = [];
for (const [path, expected] of outputs) {
  let actual;
  try {
    actual = await readFile(path, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (actual === expected) continue;
  if (checkOnly) {
    stale.push(path.slice(repositoryRoot.length + 1));
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, expected);
  }
}

if (stale.length > 0) {
  console.error(`Generated native package metadata is stale:\n${stale.map((path) => `- ${path}`).join("\n")}`);
  process.exit(1);
}
console.log(checkOnly ? "native package metadata is current" : "generated native package metadata");

function runtimeKey(target) {
  const libc = target.npmPlatform === "linux"
    ? target.libc === "glibc" ? "gnu" : target.libc
    : null;
  return [target.npmPlatform, target.npmArch, libc].filter(Boolean).join("-");
}
